import { stripTypeScriptTypes } from 'node:module';
import { readFile, writeFile } from 'node:fs/promises';
import ts from 'typescript';

/** Compile explicit top-level declarations, independently of comments and source order. */
export function runtimeSource(input: string, names: readonly string[]): string {
	const source = ts.createSourceFile('runtime.ts', input, ts.ScriptTarget.Latest, true);
	const declarations = new Map<string, string>();
	for (const statement of source.statements) {
		const declared = ts.isVariableStatement(statement) ? statement.declarationList.declarations : [statement];
		for (const declaration of declared) {
			const name = (ts.isVariableDeclaration(declaration) || ts.isFunctionDeclaration(declaration) || ts.isClassDeclaration(declaration)) ? declaration.name?.getText(source) : undefined;
			if (!name || !names.includes(name)) { continue; }
			if (declarations.has(name)) { throw new Error(`Duplicate runtime declaration: ${name}`); }
			declarations.set(name, statement.getText(source).replace(/^export\s+/, ''));
		}
	}
	return stripTypeScriptTypes(names.map(name => {
		const declaration = declarations.get(name);
		if (!declaration) { throw new Error(`Missing runtime declaration: ${name}`); }
		return declaration;
	}).join('\n'), { mode: 'transform' });
}

/** Generated artifacts are checked and written through the same deterministic path. */
export async function buildRuntime({ source, output, names, exportName, generator }: { source: URL; output: URL; names: readonly string[]; exportName: string; generator: string }): Promise<void> {
	const input = await readFile(source, 'utf8');
	const result = `// Generated by ordito/scripts/${generator} from named typed declarations. Do not edit.\nexport const ${exportName} = ${JSON.stringify(runtimeSource(input, names))};\n`;
	if (process.argv.includes('--check')) {
		if (await readFile(output, 'utf8') !== result) { throw new Error(`${exportName} artifact is stale`); }
	} else {
		await writeFile(output, result);
	}
}
