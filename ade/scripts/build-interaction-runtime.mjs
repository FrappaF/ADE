import { readFile, writeFile } from 'node:fs/promises';
import { stripTypeScriptTypes } from 'node:module';
const source = new URL('../../src/vs/workbench/contrib/ade/common/modelInteractions.ts', import.meta.url);
const output = new URL('../../src/vs/workbench/contrib/ade/common/interactionRuntime.generated.ts', import.meta.url);
const input = await readFile(source, 'utf8');
const helpers = input.slice(input.indexOf('class InteractionFailure'), input.indexOf('/** Scripted responses'));
const runner = input.slice(input.indexOf('export async function executeInteractionProgram'), input.indexOf('/** Human-readable hierarchy'));
const scope = input.slice(input.indexOf('function operationScope'), input.indexOf('function booleanExpression'));
const javascript = stripTypeScriptTypes(helpers + scope + runner, { mode: 'transform' }).replace('export async function executeInteractionProgram', 'async function executeInteractionProgram');
const result = input.slice(0, input.indexOf("import {")) + '// Generated by ade/scripts/build-interaction-runtime.mjs from the typed interpreter. Do not edit.\nexport const interactionInterpreterSource = ' + JSON.stringify(javascript) + ';\n';
if (process.argv.includes('--check')) { if (await readFile(output, 'utf8') !== result) { throw new Error('Interaction runtime artifact is stale'); } }
else { await writeFile(output, result); }
